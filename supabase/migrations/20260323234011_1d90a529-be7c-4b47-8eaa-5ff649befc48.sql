## Como o Preço da Sucata é Definido?

O preço da sucata varia conforme diversos fatores:

### 1. Cotação Internacional
Os preços dos metais seguem a **London Metal Exchange (LME)**, a bolsa de metais de Londres. Quando o dólar sobe, os preços em reais tendem a subir também.

### 2. Oferta e Demanda Regional
Em regiões com muitos depósitos, a concorrência pressiona os preços de compra para cima. Já em regiões com poucos compradores, os preços de venda tendem a ser menores.

### 3. Qualidade do Material
Material limpo, separado e classificado vale significativamente mais. **Sucata mista** sempre paga menos que material separado por tipo.

### 4. Volume
Quanto maior o volume, melhor o preço por kg. Compradores de grande escala conseguem negociar valores superiores.

