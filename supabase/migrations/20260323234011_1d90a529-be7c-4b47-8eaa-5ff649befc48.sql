## Classificação do Cobre na Reciclagem

### Cobre 1 (Bright Copper)
É o cobre mais puro e mais caro. Vem de fios elétricos descascados, sem verniz e sem solda. Deve estar limpo e brilhante.

**Valor:** O mais alto da tabela (R$ 48-55/kg na compra)

### Cobre 2 (Mixed Copper)
Cobre com impurezas leves: solda, verniz fino, pequenas oxidações. Inclui fios esmaltados e cobre com patina.

**Valor:** 15-20% menor que o Cobre 1

### Cobre Queimado
Cobre que foi queimado para remover a capa plástica. Apesar de parecer limpo, perde qualidade no processo. Muitas siderúrgicas pagam menos.

**Valor:** 25-30% menor que o Cobre 1

### Fio de Cobre com Capa
Fios elétricos com a capa plástica. O rendimento de cobre varia de 40% a 70% do peso total.

**Dica:** Se o fio tem mais de 60% de rendimento, vale a pena descascar. Abaixo disso, venda com capa.

