## Calculando a Margem de Lucro

### Fórmula da Margem Bruta

**Margem = ((Preço Venda - Preço Compra) / Preço Compra) × 100**

Exemplo com alumínio:
- Compra: R$ 6,00/kg
- Venda: R$ 8,50/kg
- Margem: ((8,50 - 6,00) / 6,00) × 100 = **41,7%**

### Fórmula do Lucro Real

**Lucro Real = Receita - Custo Material - Custos Operacionais**

Custos operacionais incluem:
- Aluguel
- Funcionários
- Transporte/frete
- Energia elétrica
- Manutenção
- Sistema de gestão
- Impostos

**Erro fatal:** Muitos consideram apenas o preço do material e esquecem dos custos operacionais. Resultado: acham que estão lucrando quando na verdade estão tendo prejuízo.

