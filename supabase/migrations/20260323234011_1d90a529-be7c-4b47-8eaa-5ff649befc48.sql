## A Fórmula Básica

A fórmula para calcular o valor de uma compra de sucata é:

**Valor Total = Peso (kg) × Preço por Kg**

Exemplo:
- Peso: 350 kg de alumínio
- Preço: R$ 6,50/kg
- **Valor total: R$ 2.275,00**

Parece simples, certo? Mas existem armadilhas que a maioria não percebe.

---

## ⚠️ Os 5 Erros Mais Comuns no Cálculo

### 1. Não Descontar a Tara
A tara é o peso do recipiente, veículo ou container. Se você não desconta, **está pagando pelo peso do balde, carrinho ou caminhão** junto com o material.

**Solução:** Sempre pese o recipiente vazio antes e desconte do peso bruto.

Fórmula correta:
**Peso Líquido = Peso Bruto - Tara**

### 2. Não Considerar Impurezas
Material sujo ou com contaminantes pesa mais mas vale menos. Água em papelão, terra em ferro, plástico misturado no alumínio.

**Solução:** Aplique um percentual de desconto por impureza:
**Peso Limpo = Peso Líquido × (1 - % Impureza)**

### 3. Usar Balança Descalibrada
Uma balança com erro de 2% em 500 kg representa **10 kg de diferença**. Se o material custa R$ 6/kg, são R$ 60 perdidos em uma única pesagem.

### 4. Arredondar Sempre Para Cima
Muitos arredondam o peso para facilitar. Se fizer isso em 20 pesagens por dia, o prejuízo acumulado no mês pode ser enorme.

### 5. Não Atualizar os Preços
Os preços dos materiais oscilam semanalmente. Usar preço desatualizado pode significar comprar caro e vender barato.

