## A Venda: Comercializando o Material

### Encontrando Compradores

**Recicladoras Locais**
- Menores exigências de volume
- Relacionamento mais próximo
- Preços podem ser menores
- Logística simplificada

**Indústrias Diretas**
- Melhores preços
- Exigem grandes volumes
- Padrões de qualidade rigorosos
- Contratos de fornecimento

**Atravessadores Regionais**
- Compram diversos materiais
- Flexibilidade de volume
- Preços intermediários
- Logística facilitada

### Negociação de Preços

A negociação eficiente é crucial para sua margem.

**Fatores que Influenciam o Preço:**

1. **Volume**: Quanto maior, melhor o preço
2. **Qualidade**: Material limpo e separado vale mais
3. **Frequência**: Fornecedores constantes conseguem melhores condições
4. **Mercado**: Cotações internacionais afetam preços
5. **Logística**: Quem busca ou quem entrega
6. **Prazo de Pagamento**: À vista ou a prazo

**Estratégias de Negociação:**

- Pesquise preços em várias recicladoras
- Negocie contratos de volume
- Ofereça regularidade de fornecimento
- Invista em qualidade do material
- Acompanhe cotações do mercado

### Logística de Venda

**Opção 1: Comprador Busca**
- Você armazena até volume mínimo
- Recicladora envia caminhão
- Geralmente melhores preços
- Menos trabalho operacional

**Opção 2: Você Entrega**
- Mais flexibilidade de timing
- Pode negociar melhores preços
- Custo de transporte por sua conta
- Exige veículo próprio ou fretado

### Documentação da Venda

Para vendas formais, você precisa:

- Nota Fiscal de Venda
- Romaneio de carga (descrição do material)
- Ticket de balança (peso)
- Conhecimento de transporte (se aplicável)
- Manifesto de resíduos (dependendo do material)

