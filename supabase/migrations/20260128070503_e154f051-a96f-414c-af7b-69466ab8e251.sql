## Estratégias por Tipo de Material

### Para Ferrosos

**Volume é fundamental:**
- Margens menores exigem maior giro
- Armazene até ter volume para caminhão
- Negocie frete com a recicladora

**Separação básica:**
- Ferro comum
- Aço inox (separar por tipo se possível)
- Ferro galvanizado

### Para Não Ferrosos

**Classificação detalhada:**
- Separar por tipo e subtipo
- Remover contaminantes
- Limpar quando viável

**Agregação de valor:**
- Cobre: retirar isolamento de fios
- Alumínio: separar latinhas de outros tipos
- Bronze: identificar ligas mais valiosas

## Armazenamento Adequado

Cada tipo de material exige cuidados específicos.

### Ferrosos

- Área coberta ou descoberta (ferrugem natural)
- Separação por tipo
- Evitar mistura com não ferrosos
- Atenção ao peso acumulado no piso

### Não Ferrosos

- Área **obrigatoriamente coberta**
- Separação rigorosa por tipo
- Proteção contra umidade
- Segurança reforçada (alto valor)

## Equipamentos para Identificação

### Básicos

- **Ímã de neodímio**: Teste de ferrosos
- **Balança de precisão**: Peso específico
- **Lima ou lixa**: Revelar cor interna

### Avançados

- **Espectrômetro portátil**: Identificação precisa de ligas
- **Testador de condutividade**: Diferencia alumínio de magnésio
- **Analisador XRF**: Composição química precisa

## Impacto no Seu Negócio

A correta classificação impacta diretamente sua lucratividade.

### Erros Comuns

1. **Misturar tipos de alumínio**: Perde-se valor na venda
2. **Não identificar inox**: Vender como ferro comum
3. **Aceitar material sujo**: Paga preço cheio, vende com desconto
4. **Ignorar subtipos de cobre**: Perda significativa

