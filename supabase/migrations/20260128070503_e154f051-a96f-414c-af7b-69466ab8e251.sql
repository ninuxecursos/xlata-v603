  '# Diferença Entre Sucata Ferrosa e Não Ferrosa: Guia Completo de Classificação

Saber diferenciar **sucata ferrosa de não ferrosa** é uma habilidade fundamental para quem trabalha com reciclagem de metais. Essa classificação impacta diretamente no preço que você paga e recebe, na forma de armazenamento e até na estratégia comercial do seu ferro velho.

Neste guia completo, vamos explicar as diferenças entre os dois tipos, como identificar cada um na prática e as melhores estratégias para maximizar seu lucro com cada categoria.

## O Que Define Sucata Ferrosa e Não Ferrosa

A classificação é simples na teoria, mas exige conhecimento prático para aplicar corretamente.

### Sucata Ferrosa

São todos os metais que contêm **ferro** em sua composição principal:

- **Ferro fundido**: Peças de máquinas, fogões, grades
- **Aço carbono**: Chapas, perfis, estruturas
- **Aço inoxidável**: Pias, panelas, equipamentos industriais
- **Ferro galvanizado**: Calhas, telhas, postes

**Características principais:**
- Atraídos por ímã (exceto inox austenítico)
- Oxidam facilmente (enferrujam)
- Maior peso específico
- Preço por kg geralmente menor

### Sucata Não Ferrosa

São metais que **não contêm ferro** ou contêm quantidades insignificantes:

- **Alumínio**: Latas, panelas, perfis, cabos
- **Cobre**: Fios, tubos, motores, transformadores
- **Bronze**: Torneiras, válvulas, buchas
- **Latão**: Fechaduras, torneiras, decorações
- **Chumbo**: Baterias, soldas, contrapesos
- **Zinco**: Calhas, telhas, galvanização
- **Estanho**: Soldas, latas de conserva

**Características principais:**
- Não são atraídos por ímã
- Maior resistência à corrosão
- Geralmente mais leves
- Preço por kg significativamente maior

## Como Identificar na Prática

Existem testes simples que você pode fazer no dia a dia do ferro velho.

### Teste do Ímã

O teste mais básico e eficiente:

1. **Aproxime um ímã forte** do material
2. **Se atrair**: Provavelmente ferroso
3. **Se não atrair**: Provavelmente não ferroso

**Exceções importantes:**
- Inox austenítico (304, 316) NÃO é atraído por ímã, mas contém ferro
- Níquel puro NÃO é atraído, mas o níquel em ligas pode ser

### Teste Visual

Características visuais ajudam na identificação:

| Material | Cor | Brilho | Oxidação |
|----------|-----|--------|----------|
| Ferro | Cinza escuro | Opaco | Ferrugem marrom |
| Alumínio | Prateado | Brilhante | Oxidação branca |
| Cobre | Avermelhado | Brilhante | Verde (azinhavre) |
| Bronze | Dourado escuro | Brilhante | Verde |
| Latão | Amarelo dourado | Brilhante | Escurecimento |

### Teste de Peso

O peso relativo ajuda na identificação:

- **Alumínio**: Muito leve (2,7 g/cm³)
- **Ferro/Aço**: Pesado (7,8 g/cm³)
- **Cobre**: Muito pesado (8,9 g/cm³)
- **Chumbo**: Extremamente pesado (11,3 g/cm³)

### Teste de Som

Ao bater no material:

- **Alumínio**: Som agudo, vibrante
- **Ferro**: Som grave, curto
- **Cobre**: Som médio, ressonante
- **Chumbo**: Som abafado, sem vibração

