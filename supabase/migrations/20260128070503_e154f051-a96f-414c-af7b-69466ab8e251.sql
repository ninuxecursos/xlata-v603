## Perguntas Frequentes

**Todo material magnético é ferroso?**
Sim, com raras exceções. Se atrai ímã, contém ferro.

**Inox é ferroso ou não ferroso?**
Tecnicamente ferroso (contém ferro), mas comercialmente tratado como categoria especial pelo valor.

**Como saber se é bronze ou latão?**
Bronze é mais avermelhado e pesado. Latão é mais amarelado. O preço do bronze geralmente é maior.

**Alumínio pintado vale menos?**
Sim, a tinta representa peso morto e custo de remoção.

