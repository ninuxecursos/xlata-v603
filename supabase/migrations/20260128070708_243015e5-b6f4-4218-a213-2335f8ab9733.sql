  '# Erros Comuns na Gestão de Ferro Velho: Como Evitar e Corrigir

Gerenciar um **ferro velho** pode parecer simples: compra material, armazena e vende. Mas a realidade é bem diferente. Pequenos erros de gestão se acumulam ao longo do tempo e podem transformar um negócio potencialmente lucrativo em uma operação que mal consegue pagar as contas.

Neste artigo, vamos expor os erros mais comuns que observamos em ferro velhos de todo o Brasil — e, mais importante, como evitá-los ou corrigi-los.

## Erro 1: Não Separar Dinheiro Pessoal do Negócio

Este é, disparado, o erro mais grave e mais comum.

### O Problema

O dono usa o dinheiro do caixa para pagar conta de luz de casa, abastecer o carro pessoal, comprar almoço da família. "Depois eu reponho", ele pensa.

### As Consequências

- Nunca sabe se o negócio está lucrando
- Pode estar cobrindo prejuízos sem perceber
- Impossível fazer planejamento financeiro
- Problemas com fisco (mistura de patrimônios)

### A Solução

1. **Abra conta bancária separada** para a empresa
2. **Defina um pró-labore** (seu salário fixo)
3. **Retire apenas o combinado** na data certa
4. **Use cartão empresarial** para despesas da empresa

## Erro 2: Comprar Sem Saber o Preço de Venda

### O Problema

O catador chega com uma carga de material. O dono, sem pesquisar, paga o preço que o fornecedor pede. Dias depois, descobre que vai vender por menos do que pagou.

### As Consequências

- Compra material com prejuízo
- Estoque de materiais não lucrativos
- Dinheiro parado em material que não vale a pena

### A Solução

1. **Mantenha tabela de preços atualizada** (compra e venda)
2. **Calcule a margem mínima** antes de comprar
3. **Negocie com fornecedores** baseado em dados
4. **Recuse material** quando a conta não fechar

## Erro 3: Não Controlar Estoque

### O Problema

Material entra, material sai, mas ninguém sabe exatamente quanto tem de cada coisa. O pátio está cheio, mas o caixa está vazio.

### As Consequências

- Não sabe quanto investiu em cada material
- Material parado demais perde valor ou se deteriora
- Pode estar comprando o que já tem demais
- Vende sem saber a margem real

### A Solução

1. **Registre toda entrada** com tipo, peso e valor
2. **Registre toda saída** igualmente
3. **Faça inventário** físico regularmente
4. **Use sistema de gestão** para controle automático

## Erro 4: Ignorar a Classificação Correta

### O Problema

Todo alumínio vai para a mesma pilha. Todo cobre vai junto. Na hora de vender, a recicladora paga pelo tipo de menor valor.

### As Consequências

- Perde dinheiro na venda (mistura deprecia o preço)
- Compra pagando preço de material puro, vende como misto
- Margem de lucro cai drasticamente

### A Solução

1. **Treine a equipe** para identificar subtipos
2. **Separe por categoria** desde a entrada
3. **Armazene separadamente** cada tipo
4. **Negocie por tipo** na venda

## Erro 5: Não Emitir Documentos

### O Problema

Compra sem recibo, vende sem nota. "Todo mundo faz assim, nunca deu problema."

### As Consequências

- Risco de acusação de receptação
- Impossível comprovar origem do material
- Problemas com fiscalização ambiental
- Dificuldade para vender a grandes compradores

### A Solução

1. **Emita recibo** para toda compra de pessoa física
2. **Exija nota fiscal** de compras de empresas
3. **Emita nota fiscal** nas vendas
4. **Mantenha livro de registro** organizado

## Erro 6: Falta de Manutenção de Equipamentos

### O Problema

A balança está descalibrada. A prensa quebra no meio da operação. O caminhão fica na oficina quando mais precisa.

### As Consequências

- Pesa errado (paga mais ou recebe menos)
- Paradas inesperadas prejudicam operação
- Custos de conserto maiores que manutenção preventiva
- Perda de credibilidade com fornecedores

### A Solução

1. **Calibre a balança** regularmente (INMETRO)
2. **Faça manutenção preventiva** nos equipamentos
3. **Tenha peças de reposição** básicas
4. **Reserve verba mensal** para manutenção

## Erro 7: Depender de Poucos Compradores

### O Problema

Vende tudo para uma única recicladora. Quando ela atrasa pagamento ou baixa preços, você está preso.

### As Consequências

- Vulnerabilidade a mudanças de preço
- Risco de calote sem alternativas
- Menor poder de negociação
- Dependência perigosa

### A Solução

1. **Diversifique compradores** para cada material
2. **Pesquise preços** regularmente
3. **Mantenha relacionamento** com múltiplas recicladoras
4. **Negocie contratos** que garantam condições

## Erro 8: Não Investir em Segurança

### O Problema

Ferro velho com material valioso exposto, sem câmeras, sem controle de acesso. Furtos acontecem sem que ninguém perceba.

### As Consequências

- Perdas por furto externo
- Desvios por funcionários
- Material some sem explicação
- Prejuízo contínuo e silencioso

### A Solução

1. **Instale câmeras** em pontos estratégicos
2. **Controle o acesso** ao pátio
3. **Armazene materiais valiosos** em local seguro
4. **Faça conferências** regulares de estoque

## Erro 9: Gestão Informal de Funcionários

### O Problema

Funcionários sem registro, sem horário definido, sem responsabilidades claras. Cada um faz o que quer.

### As Consequências

- Riscos trabalhistas enormes
- Baixa produtividade
- Erros por falta de treinamento
- Conflitos e turnover alto

### A Solução

1. **Registre todos os funcionários** corretamente
2. **Defina funções** e responsabilidades
3. **Treine para as tarefas** específicas
4. **Estabeleça rotinas** e procedimentos

## Erro 10: Não Acompanhar o Mercado

### O Problema

Opera da mesma forma há 20 anos. Não sabe que preços mudaram, que novos materiais surgiram, que concorrentes evoluíram.

### As Consequências

- Perde oportunidades de novos materiais
- Paga preços defasados
- Concorrência mais eficiente cresce
- Negócio estagna ou declina

### A Solução

1. **Acompanhe cotações** de metais
2. **Converse com outros** empresários do setor
3. **Visite feiras** e eventos de reciclagem
4. **Invista em tecnologia** e sistemas

