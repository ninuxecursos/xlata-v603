## Dicas para Agilizar o Licenciamento

### 1. Prepare Toda Documentação Antes

Documentação incompleta é a maior causa de atrasos. Confira tudo antes de protocolar.

### 2. Contrate Profissional Qualificado

Um consultor ambiental experiente conhece os procedimentos e evita retrabalhos.

### 3. Escolha Bem a Localização

Evite áreas de preservação, mananciais e zonas residenciais exclusivas.

### 4. Acompanhe o Processo

Faça follow-up regular com o órgão ambiental. Responda prontamente a solicitações.

### 5. Mantenha Regularidade

Após obter a licença, cumpra todas as condicionantes. A renovação depende disso.

## Renovação da Licença

A LO precisa ser renovada periodicamente.

### Prazo para Solicitação

- Solicite renovação com 120 dias de antecedência
- Protocolando no prazo, pode operar até decisão final

### Documentos para Renovação

- Requerimento de renovação
- Licença anterior
- Relatório de cumprimento das condicionantes
- PGRS atualizado
- Certidões atualizadas

### Condicionantes Comuns

- Manter área impermeabilizada
- Sistema de drenagem funcionando
- Controle de vetores ativo
- Documentação de compras e vendas em dia

## Perguntas Frequentes

**Posso operar enquanto aguardo a licença?**
Não. Operar sem licença é infração ambiental, mesmo com processo em andamento.

**Quanto custa o licenciamento completo?**
Entre R$ 3.000 e R$ 30.000, dependendo do porte e estado.

**Preciso de licença para ferro velho pequeno?**
Sim, mas pode ser licenciamento simplificado dependendo do porte e estado.

**A licença é vitalícia?**
Não. A LO tem validade de 4 a 10 anos e precisa ser renovada.

