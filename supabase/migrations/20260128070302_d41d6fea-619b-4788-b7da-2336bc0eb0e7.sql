  '# CNAE para Ferro Velho e Reciclagem: Qual o Código Correto para Sua Empresa

Escolher o **CNAE correto para ferro velho e reciclagem** é uma decisão que impacta diretamente os impostos que você vai pagar, as licenças que precisa obter e até sua capacidade de emitir notas fiscais. Muitos empresários do setor cometem erros na escolha do código, gerando problemas fiscais e operacionais.

Neste artigo completo, vamos explicar todos os CNAEs aplicáveis ao setor de sucata e reciclagem, suas diferenças e como escolher o mais adequado para sua operação.

## O Que É CNAE e Por Que É Importante

O CNAE (Classificação Nacional de Atividades Econômicas) é um código padronizado que identifica a atividade principal da sua empresa. Ele é utilizado por:

- **Receita Federal**: Para definição de tributos
- **Estados**: Para cálculo de ICMS e substituição tributária
- **Prefeituras**: Para ISS e alvará de funcionamento
- **Órgãos ambientais**: Para licenciamento
- **Bancos**: Para análise de crédito
- **Fornecedores e clientes**: Para emissão de notas fiscais

### Consequências de Escolher o CNAE Errado

Usar um CNAE inadequado pode resultar em:

1. **Tributação incorreta**: Pagar mais ou menos impostos do que deveria
2. **Problemas com licenciamento**: Licença ambiental incompatível
3. **Multas fiscais**: Por enquadramento tributário errado
4. **Dificuldade para emitir NF**: Código não compatível com a operação
5. **Problemas trabalhistas**: Enquadramento sindical incorreto

## Principais CNAEs para Ferro Velho e Reciclagem

Existem diversos códigos CNAE que podem ser utilizados no setor. A escolha depende do tipo de operação que você realiza.

### CNAEs de Comércio (Compra e Venda)

Estes são os mais utilizados por ferro velhos tradicionais:

**4687-7/03 - Comércio atacadista de resíduos e sucatas metálicos**
- Abrange: ferro, aço, alumínio, cobre, bronze, latão
- Ideal para: ferro velhos focados em metais
- Tributação: ICMS sobre operações interestaduais

**4687-7/02 - Comércio atacadista de resíduos e sucatas não metálicos**
- Abrange: plástico, papel, papelão, vidro
- Ideal para: depósitos que trabalham com diversos materiais
- Pode ser usado como secundário

**4686-9/02 - Comércio atacadista de embalagens**
- Específico para embalagens usadas
- Pode complementar operações de papel e plástico

### CNAEs de Recuperação (Processamento)

Se você faz algum tipo de beneficiamento ou processamento:

**3831-9/01 - Recuperação de sucatas de alumínio**
- Para quem processa alumínio (prensa, separa, beneficia)
- Exige licenciamento específico

**3831-9/99 - Recuperação de materiais metálicos, exceto alumínio**
- Para processamento de outros metais
- Operações de prensagem, corte, separação

**3832-7/00 - Recuperação de materiais plásticos**
- Processamento de plásticos recicláveis
- Moagem, lavagem, separação

**3839-4/99 - Recuperação de materiais não especificados anteriormente**
- Abrange outros materiais recicláveis
- Uso complementar

### CNAEs de Coleta

Para empresas que fazem coleta de materiais:

**3811-4/00 - Coleta de resíduos não perigosos**
- Coleta em empresas e domicílios
- Requer veículos cadastrados

**4930-2/01 - Transporte rodoviário de carga**
- Para transporte de materiais
- Exige RNTRC (Registro Nacional de Transportadores)

## Como Escolher o CNAE Correto

A escolha do CNAE principal deve refletir sua **atividade predominante**.

### Passo 1: Identifique Sua Operação Principal

Pergunte-se:

- **Você compra e vende sucata sem processar?** → CNAE 4687-7/03 ou 4687-7/02
- **Você processa ou beneficia materiais?** → CNAEs da série 38xx
- **Você faz coleta em empresas/residências?** → CNAE 3811-4/00
- **Você só transporta materiais?** → CNAE 4930-2/01

### Passo 2: Defina CNAEs Secundários

Você pode ter múltiplos CNAEs. Por exemplo:

**Exemplo de Ferro Velho Tradicional:**
- Principal: 4687-7/03 (Comércio de sucatas metálicos)
- Secundário: 4687-7/02 (Comércio de sucatas não metálicos)
- Secundário: 3831-9/99 (Recuperação de materiais metálicos)

**Exemplo de Depósito com Coleta:**
- Principal: 4687-7/03 (Comércio de sucatas metálicos)
- Secundário: 3811-4/00 (Coleta de resíduos)
- Secundário: 4930-2/01 (Transporte de carga)

### Passo 3: Consulte um Contador

Sempre valide sua escolha com um contador especializado. Ele pode orientar sobre:

- Impactos tributários de cada CNAE
- Enquadramento no Simples Nacional
- Obrigações acessórias

## Tributação por CNAE

O CNAE impacta diretamente sua carga tributária.

### Simples Nacional

A maioria dos CNAEs de reciclagem pode optar pelo Simples Nacional:

| CNAE | Anexo | Alíquota Inicial |
|------|-------|------------------|
| 4687-7/03 | Anexo I | 4,00% |
| 4687-7/02 | Anexo I | 4,00% |
| 3831-9/01 | Anexo II | 4,50% |
| 3831-9/99 | Anexo II | 4,50% |
| 3811-4/00 | Anexo III | 6,00% |

### Lucro Presumido

Para empresas maiores ou que não optam pelo Simples:

- IRPJ: 15% sobre 8% do faturamento (1,2% efetivo)
- CSLL: 9% sobre 12% do faturamento (1,08% efetivo)
- PIS: 0,65%
- COFINS: 3%
- ICMS: Varia por estado (geralmente 12-18%)

### Diferimento de ICMS

Em muitos estados, operações com sucata têm **diferimento de ICMS**, ou seja, o imposto é pago apenas pelo comprador final (indústria). Isso melhora significativamente o fluxo de caixa.

Estados com diferimento para sucata:
- São Paulo
- Minas Gerais
- Paraná
- Rio Grande do Sul
- Santa Catarina

## CNAE e Licenciamento Ambiental

O CNAE escolhido impacta o tipo de licença ambiental necessária.

### Atividades de Baixo Impacto

CNAEs de comércio (4687-7/xx) geralmente exigem:
- Licenciamento simplificado
- Dispensa de EIA/RIMA
- Processo mais rápido

### Atividades de Maior Impacto

CNAEs de recuperação (38xx) podem exigir:
- Licenciamento completo (LP, LI, LO)
- Estudos ambientais específicos
- Monitoramento contínuo

## CNAE e MEI

**Atenção**: A atividade de ferro velho **não pode ser enquadrada como MEI** (Microempreendedor Individual).

Os CNAEs de comércio de sucata e reciclagem não constam na lista de atividades permitidas para MEI. Você precisará abrir pelo menos uma ME (Microempresa).

## Como Alterar o CNAE

Se você percebeu que está com o CNAE errado, é possível alterar:

1. **Consulte um contador** para avaliar impactos
2. **Faça alteração contratual** na Junta Comercial
3. **Atualize na Receita Federal** via DBE
4. **Atualize na Prefeitura** e órgão ambiental
5. **Comunique fornecedores e clientes**

O processo leva de 1 a 4 semanas, dependendo do estado.

## Perguntas Frequentes

**Posso ter mais de um CNAE?**
Sim, você pode ter um CNAE principal e vários secundários. Isso é comum e recomendado para quem trabalha com diversos materiais.

**O CNAE afeta minha nota fiscal?**
Sim. A nota fiscal precisa ser compatível com seu CNAE. Operações fora do escopo podem ser recusadas.

**Posso mudar de CNAE depois?**
Sim, mas envolve alteração contratual e pode impactar tributação e licenças.

**Qual CNAE devo usar para sucata eletrônica?**
O CNAE 4687-7/03 geralmente cobre, mas consulte sobre 3831-9/99 se fizer desmontagem.

## Conclusão

A escolha do CNAE correto para seu ferro velho ou depósito de reciclagem é fundamental para operar de forma regular e otimizada. O código impacta tributos, licenças e sua capacidade operacional.

Para a maioria dos ferro velhos tradicionais, o **CNAE 4687-7/03** (Comércio atacadista de resíduos e sucatas metálicos) é o mais adequado, complementado pelo **4687-7/02** para materiais não metálicos.

Sempre consulte um contador especializado antes de definir seus CNAEs, e mantenha seu [sistema de gestão](/solucoes/sistema-para-ferro-velho) atualizado com as informações fiscais corretas para evitar problemas com a emissão de documentos.

