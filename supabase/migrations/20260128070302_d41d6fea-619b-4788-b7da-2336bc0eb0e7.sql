Operar um ferro velho ou depósito de sucata sem as devidas **licenças ambientais** é um dos erros mais graves que um empresário do setor pode cometer. Além das multas que podem chegar a milhões de reais, há risco de fechamento do estabelecimento e até processo criminal.

Neste guia completo, vamos explicar todo o processo de licenciamento ambiental para atividades de reciclagem e sucata, desde os documentos necessários até dicas para agilizar a obtenção.

## Por Que Licença Ambiental É Obrigatória

A atividade de comércio e processamento de sucata é considerada **potencialmente poluidora** pela legislação brasileira. Isso porque envolve:

- Armazenamento de materiais que podem contaminar solo e água
- Risco de incêndio
- Geração de resíduos secundários
- Potencial atração de vetores (roedores, insetos)
- Impacto visual e sonoro

### Base Legal

A obrigatoriedade do licenciamento está prevista em:

- **Lei 6.938/81**: Política Nacional do Meio Ambiente
- **Resolução CONAMA 237/97**: Procedimentos de licenciamento
- **Lei 9.605/98**: Crimes ambientais
- **Legislações estaduais**: Cada estado tem suas normas específicas

### Penalidades por Operar Sem Licença

Quem opera sem licença ambiental está sujeito a:

| Infração | Penalidade |
|----------|------------|
| Operar sem licença | Multa de R$ 500 a R$ 10.000.000 |
| Causar poluição | Multa de R$ 5.000 a R$ 50.000.000 |
| Crime ambiental | Detenção de 1 a 6 meses |
| Reincidência | Multa em dobro + fechamento |

## Tipos de Licenças Ambientais

O licenciamento ambiental segue um processo trifásico, cada etapa com sua licença específica.

### Licença Prévia (LP)

A primeira fase do licenciamento.

**O que atesta:**
- Viabilidade ambiental do empreendimento
- Localização adequada
- Concepção do projeto aprovada

**Documentos necessários:**
- Requerimento padrão do órgão ambiental
- Certidão de uso do solo (Prefeitura)
- Croqui de localização
- Memorial descritivo do empreendimento
- Comprovante de propriedade ou locação

**Prazo de obtenção:** 30 a 120 dias
**Validade:** 2 a 5 anos
**Custo médio:** R$ 500 a R$ 3.000

### Licença de Instalação (LI)

Segunda fase, autoriza a instalação.

**O que autoriza:**
- Construção ou adaptação do espaço
- Instalação de equipamentos
- Preparação da infraestrutura

**Documentos necessários:**
- LP válida
- Projeto executivo
- Plano de Gerenciamento de Resíduos Sólidos (PGRS)
- Projeto de prevenção de incêndio
- ART do responsável técnico

**Prazo de obtenção:** 30 a 90 dias
**Validade:** 2 a 6 anos
**Custo médio:** R$ 1.000 a R$ 8.000

### Licença de Operação (LO)

Fase final, autoriza o funcionamento.

**O que autoriza:**
- Início das atividades
- Operação efetiva do empreendimento
- Comercialização de materiais

**Documentos necessários:**
- LI válida
- Comprovação de execução conforme projeto
- Certidão dos Bombeiros
- Alvará de funcionamento
- Registro no Cadastro Técnico Federal (IBAMA)

**Prazo de obtenção:** 30 a 90 dias
**Validade:** 4 a 10 anos (renovável)
**Custo médio:** R$ 1.500 a R$ 12.000

## Licenciamento Simplificado

Muitos estados oferecem licenciamento simplificado para atividades de baixo impacto.

### Licença Ambiental Única (LAU)

Alguns estados unificam as três licenças:
- São Paulo (CETESB)
- Paraná (IAT)
- Santa Catarina (IMA)

**Vantagens:**
- Processo único
- Prazo menor (60-120 dias)
- Custo reduzido
- Menos burocracia

### Declaração de Dispensa

Para pequenos estabelecimentos, alguns estados permitem:
- Declaração de dispensa de licenciamento
- Cadastro simplificado
- Termo de compromisso ambiental

**Critérios comuns:**
- Área até 200-500 m²
- Sem processamento industrial
- Apenas armazenamento temporário

## Documentação Necessária

Prepare todos os documentos antes de iniciar o processo.

### Documentos do Empreendimento

- CNPJ atualizado
- Contrato social e alterações
- Comprovante de endereço
- Contrato de locação ou escritura
- Certidão de uso e ocupação do solo

### Documentos Técnicos

- Memorial descritivo das atividades
- Layout do estabelecimento
- Fluxograma operacional
- Plano de Gerenciamento de Resíduos Sólidos (PGRS)
- Projeto de prevenção de incêndio

### Documentos do Responsável Técnico

- ART (Anotação de Responsabilidade Técnica)
- Registro profissional (CREA, CRQ, etc.)
- Certidão de regularidade do conselho

## Plano de Gerenciamento de Resíduos Sólidos (PGRS)

O PGRS é documento obrigatório e deve conter:

### Conteúdo Mínimo

1. **Identificação do empreendimento**
   - Razão social e CNPJ
   - Endereço e contatos
   - Responsável técnico

2. **Descrição das atividades**
   - Tipos de materiais recebidos
   - Processos realizados
   - Capacidade de armazenamento

3. **Diagnóstico dos resíduos**
   - Classificação (perigosos e não perigosos)
   - Quantidades estimadas
   - Características

4. **Procedimentos operacionais**
   - Recebimento e triagem
   - Armazenamento
   - Expedição

5. **Destinação final**
   - Compradores e destinatários
   - Licenças dos destinatários
   - Rastreabilidade

6. **Monitoramento**
   - Indicadores
   - Frequência de avaliação
   - Ações corretivas

