## O Que É um Ferro Velho e Como Funciona

Um ferro velho, também conhecido como depósito de sucata ou depósito de reciclagem, é um estabelecimento comercial especializado na **compra, armazenamento e venda de materiais recicláveis**. O modelo de negócio é relativamente simples: você compra materiais de catadores, pequenos coletores e até indústrias, e depois revende para recicladoras e fundições.

### O Ciclo do Material Reciclável

O funcionamento de um ferro velho segue um ciclo bem definido:

1. **Entrada de Material**: Catadores, coletores e empresas trazem materiais como ferro, alumínio, cobre, plástico e papel
2. **Pesagem e Avaliação**: O material é pesado e avaliado quanto à qualidade e tipo
3. **Pagamento**: O fornecedor recebe o pagamento baseado no peso e preço por quilo
4. **Separação e Classificação**: Os materiais são separados por tipo e qualidade
5. **Armazenamento**: O material fica estocado até atingir volume para venda
6. **Venda para Recicladores**: Quando há volume suficiente, o material é vendido para indústrias recicladoras

### Tipos de Materiais Mais Comercializados

Os principais materiais comercializados em ferro velhos incluem:

- **Metais Ferrosos**: Ferro, aço, chapas, perfis
- **Metais Não-Ferrosos**: Alumínio, cobre, bronze, latão, inox
- **Plásticos**: PET, PEAD, PP, PVC
- **Papel e Papelão**: Papel branco, papelão ondulado
- **Eletrônicos**: Sucata eletrônica (e-lixo)

## Legislação e Regularização do Ferro Velho

Um dos aspectos mais importantes para quem quer operar um ferro velho de forma profissional é a **regularização junto aos órgãos competentes**. Atuar na informalidade pode trazer multas pesadas e até o fechamento do estabelecimento.

### CNAE Correto para Ferro Velho

O CNAE (Classificação Nacional de Atividades Econômicas) mais utilizado para ferro velho é:

- **4687-7/03**: Comércio atacadista de resíduos e sucatas metálicos
- **4687-7/02**: Comércio atacadista de resíduos e sucatas não metálicos

A escolha do CNAE correto impacta diretamente nos impostos que você vai pagar e nas licenças que precisa obter.

### Licenças Ambientais Necessárias

Para operar legalmente, você precisará de:

1. **Licença Prévia (LP)**: Fase inicial do licenciamento
2. **Licença de Instalação (LI)**: Autoriza a instalação do empreendimento
3. **Licença de Operação (LO)**: Autoriza o funcionamento efetivo

Cada estado tem suas especificidades, mas em geral você precisará apresentar:

- Projeto de gerenciamento de resíduos
- Comprovação de destinação adequada
- Laudos técnicos ambientais
- Alvará de funcionamento

### Documentação Obrigatória

Todo ferro velho regularizado deve manter:

- Livro de registro de compras
- Notas fiscais de entrada e saída
- Comprovantes de destinação final
- Cadastro de fornecedores

## Como Calcular o Lucro no Ferro Velho

Uma das maiores dificuldades de quem opera ferro velho é saber exatamente **quanto está lucrando**. Muitos empresários do setor trabalham "no escuro", sem saber se estão tendo lucro ou prejuízo.

### A Fórmula Básica do Lucro

O cálculo do lucro no ferro velho segue uma fórmula simples:

**Lucro = Preço de Venda - Preço de Compra - Custos Operacionais**

Porém, para chegar a esse número, você precisa controlar:

- Preço médio de compra por material
- Preço de venda para cada recicladora
- Custos fixos (aluguel, funcionários, energia)
- Custos variáveis (transporte, manutenção)

### Margens de Lucro por Material

As margens variam muito conforme o material:

| Material | Margem Média |
|----------|--------------|
| Cobre | 15-25% |
| Alumínio | 20-35% |
| Ferro | 10-20% |
| Plástico | 25-40% |
| Papel | 15-30% |

Sistemas de gestão como o [XLata](/solucoes/sistema-para-ferro-velho), desenvolvido especificamente para ferro velho e reciclagem, permitem acompanhar essas margens em tempo real e tomar decisões baseadas em dados.

## Erros Comuns na Gestão de Ferro Velho

Ao longo de anos observando o mercado, identificamos os erros mais frequentes que levam ferro velhos ao prejuízo:

### 1. Não Separar Dinheiro Pessoal do Negócio

Misturar as finanças pessoais com as do ferro velho é receita para desastre. Você nunca vai saber se o negócio está dando lucro ou se você está usando dinheiro próprio para cobrir prejuízos.

### 2. Comprar Sem Verificar Preços de Venda

Antes de comprar qualquer material, você precisa saber por quanto vai conseguir vender. Comprar sem essa informação é jogar dinheiro fora.

### 3. Não Controlar o Estoque

Materiais parados no pátio representam dinheiro parado. Além disso, alguns materiais se deterioram com o tempo, especialmente papel e alguns plásticos.

### 4. Ignorar a Classificação Correta

Misturar tipos de alumínio, por exemplo, pode fazer você perder dinheiro na venda. Cada tipo tem preço diferente.

### 5. Não Emitir Documentos

Além de ser obrigatório, a documentação protege você contra acusações de receptação e permite comprovar a origem dos materiais.

