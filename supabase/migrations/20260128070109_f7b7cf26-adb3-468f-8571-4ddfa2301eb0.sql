Não. Operar sem licença ambiental é crime e pode resultar em multas pesadas.

**Preciso de contador?**
Sim, é altamente recomendado ter um contador desde o início para evitar problemas fiscais.

**Qual o faturamento mínimo para ser viável?**
Depende dos custos fixos, mas geralmente a partir de R$ 30.000/mês já é possível ter lucro.

**Posso abrir ferro velho em área residencial?**
Geralmente não. Consulte o zoneamento da sua cidade.

